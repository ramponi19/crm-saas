-- Contadores da conversa (substitui sincronizar_nao_lidas e tg_lead_marcos_conversa).
create function public.core_mensagens_sincroniza() returns trigger
  language plpgsql security definer
  set search_path to 'public', 'pg_temp'
as $$
declare
  v_conversa bigint := coalesce(new.conversa_id, old.conversa_id);
begin
  if tg_op = 'INSERT' then
    update conversas c set
      ultima_mensagem_at = greatest(coalesce(c.ultima_mensagem_at, new.created_at), new.created_at),
      ultima_recebida_at = case when new.direcao = 'recebida'
        then greatest(coalesce(c.ultima_recebida_at, new.created_at), new.created_at) else c.ultima_recebida_at end,
      ultima_enviada_at = case when new.direcao = 'enviada'
        then greatest(coalesce(c.ultima_enviada_at, new.created_at), new.created_at) else c.ultima_enviada_at end
     where c.id = v_conversa;
  end if;
  update conversas c
     set nao_lidas = (select count(*) from mensagens m
                       where m.conversa_id = v_conversa and m.direcao = 'recebida' and not m.lida)
   where c.id = v_conversa
     and c.nao_lidas is distinct from (select count(*) from mensagens m
                       where m.conversa_id = v_conversa and m.direcao = 'recebida' and not m.lida);
  return coalesce(new, old);
end $$;

