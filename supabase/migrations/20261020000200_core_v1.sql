-- =====================================================================================
-- core v1 — 16 tabelas do core, interfaces core_* e as funções de produção que ficam.
-- Base: aba "Desenho do core v1" do doc "Nexus — Inventário para a reconstrução" e
-- docs/reconstrucao-nexus/04-INTERFACES-E-REGRAS.md (19/10/2026).
--
-- Esta migração SÓ CRIA. Não altera nenhuma tabela existente; a passagem dos dados
-- (e a troca de leads/clientes/lead_mensagens por views) é supabase/scripts/migrar_jm_para_core.sql.
--
-- Escolhas onde o desenho deixou em aberto (registradas aqui, não perguntadas):
--  1. Policies: uma por ação (select/insert/update/delete), sempre com
--     empresa_id = (select get_empresa_id()). Nas tabelas que têm loja (contatos, negocios,
--     conversas, mensagens, itens, eventos, canais) a mesma policy também filtra
--     (select filiais_visiveis()) @> array[coalesce(filial_id,0)], igual à produção hoje.
--     Sem isso a cópia afrouxaria o isolamento entre lojas (vendedor de uma loja veria a outra).
--     Em itens, eventos e canais, filial_id nulo = registro da rede, visível a todas as lojas
--     (produto do catálogo, evento da empresa); por isso essas duas não têm gatilho de loja.
--  2. Tabelas 1:1 com a empresa (empresa_branding, empresa_menu, empresa_dados_contrato,
--     empresa_modulos) e campos_personalizados não têm filial_id: são da empresa, não da loja.
--     Escrita nelas e em campos_personalizados exige is_empresa_admin(empresa_id).
--  3. presets_onboarding não tem empresa_id (o desenho manda): leitura para authenticated
--     só dos ativos; escrita só superadmin.
--  4. FK de empresa_id com ON DELETE CASCADE nas tabelas novas: hard_delete_empresa continua
--     funcionando sem conhecer as tabelas novas.
--  5. Chaves de `dados` que começam com "_" são reservadas ao sistema (legado da migração,
--     estruturas jsonb sem tipo em campos_personalizados) e não passam pela validação.
--     Toda outra chave precisa existir em campos_personalizados (empresa, entidade, chave, ativo).
--  6. "Funções novas STABLE": todas as que só leem são STABLE. As que gravam
--     (core_evento_emitir, core_fundir_contatos e os gatilhos que atualizam outra tabela)
--     não podem ser STABLE e ficam VOLATILE.
--  7. REVOKE EXECUTE de PUBLIC, anon e authenticated em toda função nova; GRANT só a
--     service_role. Nas funções de produção reescritas, authenticated mantém EXECUTE apenas
--     onde o app logado depende dela (policies de RLS e RPC chamado pela sessão do usuário):
--     get_empresa_id, is_super_admin, is_empresa_admin, filial_atual, filiais_visiveis,
--     chat_marcar_lido, chat_nao_lidas_por_conversa, set_impersonation, encerrar_impersonacao,
--     set_super_admin, hard_delete_empresa, filial_gravacao (lib/whatsapp chama com a sessão;
--     alinhado ao 20261020000000_revoke_rpc no rebase). anon perde EXECUTE em todas.
--     Fora as reescritas, authenticated segue com as 22 do revoke_rpc (RPCs do ZapIntel e
--     buscar_lead_por_numero não são tocadas aqui).
--  8. Regra de limite (#26/P1): core_limite_negocios em negocios conta status='aberto' contra
--     planos_config.limite_leads; empresas.limite_leads só vale como override quando > 0
--     (hoje a JM tem 0 nessa coluna, e 0 no navegador já significa "sem override").
--     A mensagem continua 'LEAD_LIMIT_REACHED', que o app já trata.
--  9. contato_identidades.canal_id, conversas.canal_id e mensagens.canal_id apontam para a
--     tabela nova `canais`; conversas usa UNIQUE NULLS NOT DISTINCT (conversa sem canal = uma só).
-- 10. Colunas de usuário em históricos (negocio_historico, eventos, contato_fusoes) não têm FK:
--      histórico não pode impedir apagar um usuário.
-- 11. ids de contatos, negocios, mensagens e canais são "generated by default": a migração
--     preserva os ids antigos (cliente → contato, lead → negócio, lead_mensagem → mensagem,
--     canal_conectado → canal) e depois reposiciona as sequências.
-- 12. rate_limit e historico_bruto continuam em public nesta migração (a ida para o schema
--     ops fica para a migração que mover o código que as usa).
-- =====================================================================================

