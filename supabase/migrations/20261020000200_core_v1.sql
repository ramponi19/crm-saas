      from empresa_modulos em join contatos c on c.empresa_id = em.empresa_id
     where c.id = p_contato and em.ativo and em.config ? 'matcher'
  loop
    continue when m.matcher !~ ('^' || m.modulo || '_[a-z0-9_]+$');
    v_fn := to_regprocedure(format('public.%I(bigint)', m.matcher));
