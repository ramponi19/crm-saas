-- ------------------------------------------------------------------ privilégios das tabelas
do $$
declare t text;
begin
  foreach t in array array['empresa_branding','empresa_modulos','empresa_menu','empresa_dados_contrato',
    'presets_onboarding','campos_personalizados','canais','contatos','contato_identidades','contato_fusoes',
    'negocios','negocio_historico','conversas','mensagens','itens','eventos'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated, service_role', t);
  end loop;
end $$;

-- ------------------------------------------------------------------ policies (uma por ação)
-- Tenant + loja: contatos, negocios, conversas, mensagens (sem loja = matriz, como produção);
-- itens e eventos (sem loja = registro da rede, visível a todas as lojas, como canais).
do $$
declare
  t text;
  ver text;
  gravar text := '(empresa_id = (select public.get_empresa_id()))';
begin
  foreach t in array array['contatos','negocios','conversas','mensagens','itens','eventos'] loop
    ver := case when t in ('itens', 'eventos')
      then '(empresa_id = (select public.get_empresa_id()) and (filial_id is null or (select public.filiais_visiveis()) @> array[filial_id]))'
      else '(empresa_id = (select public.get_empresa_id()) and (select public.filiais_visiveis()) @> array[coalesce(filial_id, 0::bigint)])' end;
    execute format('create policy %I on public.%I for select to authenticated using %s', t||'_select', t, ver);
    execute format('create policy %I on public.%I for insert to authenticated with check %s', t||'_insert', t, gravar);
    if t = 'eventos' then
      -- eventos é só de acréscimo
      execute format('create policy %I on public.%I for update to authenticated using (false)', t||'_update', t);
      execute format('create policy %I on public.%I for delete to authenticated using (false)', t||'_delete', t);
    else
      execute format('create policy %I on public.%I for update to authenticated using %s with check %s', t||'_update', t, ver, gravar);
      execute format('create policy %I on public.%I for delete to authenticated using %s', t||'_delete', t, ver);
    end if;
  end loop;
end $$;

-- Tenant sem loja, escrita livre para a equipe: contato_identidades.
