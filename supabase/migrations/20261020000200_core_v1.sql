  using (empresa_id = (select public.get_empresa_id()));

-- Históricos: leitura e acréscimo; nunca alterados.
do $$
declare t text;
begin
  foreach t in array array['contato_fusoes','negocio_historico'] loop
    execute format('create policy %I on public.%I for select to authenticated using (empresa_id = (select public.get_empresa_id()))', t||'_select', t);
    execute format('create policy %I on public.%I for insert to authenticated with check (empresa_id = (select public.get_empresa_id()))', t||'_insert', t);
    execute format('create policy %I on public.%I for update to authenticated using (false)', t||'_update', t);
    execute format('create policy %I on public.%I for delete to authenticated using (false)', t||'_delete', t);
  end loop;
end $$;

-- Configuração da empresa: todos leem, dono/admin grava.
do $$
declare
  t text;
  ler text := '(empresa_id = (select public.get_empresa_id()))';
